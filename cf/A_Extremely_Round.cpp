    for (int i = 1; i <= 999999; ++i)
    {
        if (
            [=]() -> bool
            {
                int x = i; // Make a copy
                int cnt = 0;
                while (x)
                {
                    if (x % 10 != 0)
                    {
                        cnt++;
                    }
                    x = x / 10;
                }

                return cnt == 1;
            }())
        {
            cache[i] = cache[i - 1] + 1;
        }
        else
        {
            cache[i] = cache[i - 1];
        }
    }

    int tt;
