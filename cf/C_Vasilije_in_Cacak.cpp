void solve()
{
    using ll = long long;
    /*
        12
    n k x
    5 3 10
    5 3 3  1 2 3 4 5
    10 10 55
    6 5 20  1 2 3 4 5 6
    2 1 26
    187856 87856 2609202300
    200000 190000 19000000000
    28 5 2004
    2 2 2006
    9 6 40
    47202 32455 613407217
    185977 145541 15770805980
    */
    ll N, K, X;
    cin >> N >> K >> X;
    ll mini = (K * (K + 1)) / 2;
    ll maxi = (N * (N + 1)) / 2 - ((N - K) * ((N - K) + 1)) / 2;
    dbg(mini, maxi, X);
    if (mini <= X && X <= maxi)
        cout << "YES\n";
    else
        cout << "NO\n";
}

